/** Валидация IPv4-адреса и длины префикса подсети.
 *
 * Фикс п.2.1.3/п.3: "в поле 'IP-адреса интерфейса'/'IP-адреса виртуальной машины' можно ввести
 * любые данные, а не только IP... необходимо применить исправление ко всем полям с IP... также
 * необходимо исправить все поля 'Префикс', так как в данный момент можно туда ввести любые
 * данные". Единая точка валидации — переиспользуется во всех формах с IP-полями
 * (DeviceInterfacesEditor.vue, DeviceVlanListEditor.vue, VmIpListEditor.vue,
 * ISSourcesListEditor.vue), чтобы правило было ровно одно на весь проект, а не по копии в
 * каждом компоненте с неизбежным риском разъехаться.
 *
 * Только IPv4 — весь проект ориентирован на IPv4 (см. пример "ХХХ.ХХХ.ХХХ.ХХХ/24" в
 * "Общее описание приложения"), IPv6 не поддерживается ни одной формой.
 *
 * Пустая строка считается ВАЛИДНОЙ в обеих функциях — это забота отдельной проверки на
 * "обязательность" поля (у большинства IP-полей в проекте её нет, они опциональны), а не этой:
 * задача isValidIPv4/isValidPrefixLength — только "если что-то введено, это должно быть похоже
 * на IP/префикс", а не "должно быть заполнено".
 */

/** true, если value — пустая строка или синтаксически корректный IPv4-адрес (четыре октета
 * 0-255 через точку, без ведущих нулей вроде "01" — они по RFC 3986/большинству парсеров
 * неоднозначны между десятичной и восьмеричной записью, поэтому здесь запрещены). */
export function isValidIPv4(value: string): boolean {
  const trimmed = value.trim()
  if (!trimmed) return true
  const octets = trimmed.split('.')
  if (octets.length !== 4) return false
  return octets.every((o) => /^\d{1,3}$/.test(o) && Number(o) <= 255 && (o === '0' || o[0] !== '0'))
}

/** true, если value — пустая строка/null/undefined или целое число 0-32 (длина префикса маски
 * подсети IPv4 — /0 до /32). Принимает и число, и строку: prefix_length в draft-объектах формы
 * хранится строкой (как есть из <input>), а на бэкенд перед отправкой приводится к Number. */
export function isValidPrefixLength(value: string | number | null | undefined): boolean {
  if (value === null || value === undefined) return true
  const s = String(value).trim()
  if (!s) return true
  if (!/^\d{1,2}$/.test(s)) return false
  const n = Number(s)
  return n >= 0 && n <= 32
}
