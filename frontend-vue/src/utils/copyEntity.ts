// Аудит fix/usability-batch4 (находка №3): stripIds() была определена идентичной копипастой в
// DeviceFormModal.vue, InformationSystemFormModal.vue и VMFormModal.vue — три места для одного и
// того же поведения. Вынесено сюда, чтобы следующее изменение логики (например, более глубокое
// клонирование вложенных объектов) не пришлось синхронизировать вручную в нескольких файлах.

/** Фикс п.2 (копирование сущностей): убирает id у скопированных из донора вложенных строк — с
 * чужим id backend принял бы их за попытку ОБНОВИТЬ запись донора, а не создать новую под новой
 * сущностью. Используется формами Device/VM/InformationSystem при копировании через copyFrom. */
export function stripIds<T extends { id?: string }>(rows: T[]): T[] {
  return rows.map((r) => ({ ...r, id: undefined }))
}
