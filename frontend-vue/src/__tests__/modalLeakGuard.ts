// Страж стека окон для setup.ts: после каждого теста (и после размонтирования его компонентов) стек окон обязан быть пустым.
//
// Стек окон (composables/modalLayer.ts) — состояние МОДУЛЯ, общее для всех тестов файла. Окно, оставшееся в нём, молча меняет следующие
// тесты: hasOpenModal остаётся истинным (AppShell делает фон inert), у новых окон другая глубина (--modal-depth), Esc и Tab уходят
// не туда. Пробный прогон без авто-размонтирования показал утечку в 42 из 255 спек-файлов, и ни один тест не падал.
// Остаться окно может в двух случаях: тест открыл окно и не закрыл его там, где авто-размонтирование не дотягивается (окно вне
// wrapper-а, createApp без VTU), либо mount() бросил ошибку в setup() окна уже после регистрации в стеке — в режиме разработки Vue
// такое недостроенное дерево не размонтирует (R2-05, modalStack.spec.ts).
import { hasOpenModal } from '../composables/modalLayer'

/** Бросает ошибку, если в стеке окон что-то осталось. Вызывается из setup.ts ПОСЛЕ размонтирования компонентов теста. */
export function assertNoOpenModals(): void {
  if (!hasOpenModal.value) return
  throw new Error(
    'После теста в стеке окон (composables/modalLayer.ts) осталось открытое окно. Стек общий для всех тестов файла, поэтому оно повлияет на ' +
      'следующие тесты. Закройте окно в самом тесте (событие close или wrapper.unmount()); если окно создаётся вне mount() из VTU, снимите ' +
      'его сами; если mount() бросал ошибку в setup() окна — исправьте её: недостроенное дерево Vue не размонтирует.',
  )
}
