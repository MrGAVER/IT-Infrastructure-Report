"""
Конфигурация Word-шаблона конструктора отчётов "Приложение к структурной схеме" — по образцу
документа, приложенного пользователем к задаче (3 таблицы: назначение линий связи, перечень VLAN,
перечень телекоммуникационного оборудования, под общим заголовком "Приложение к структурной схеме /
ИС <короткое имя>").

В отличие от report_seed_templates.py (точное побитовое воспроизведение регламентированного
отчёта), это заготовка ПО МОТИВАМ структуры приложенного документа, не побитовая копия:

- В исходном документе перечень VLAN сгруппирован под заголовком-строкой на каждый коммутатор
  ("Коммутатор WS-C3750G-24T (серийный номер)"), затем его VLAN построчно. Блочный докс-движок
  конструктора (report_engine.py/report_render.py: один блок-таблица — одна плоская таблица на
  одной сущности) не поддерживает вложенные заголовки строк внутри таблицы — вместо этого здесь
  плоская таблица с отдельной колонкой "Устройство" на каждой строке: тот же смысл (видно, какому
  устройству принадлежит VLAN), без группировки.
- Перечень оборудования (таблица 3) не отфильтрован по типу "сетевое оборудование", хотя заголовок
  документа подразумевает именно телекоммуникационное оборудование — типы устройств в реестре
  пользовательские (см. backend/app/services/catalogs.py: seed_defaults не создаёт справочник типов
  устройств вовсе), единого стандартного имени для фильтра нет ни в одной инсталляции гарантированно.
  Показаны все устройства; при необходимости сузить список — добавьте фильтр по нужному типу прямо
  в конструкторе (он уже открыт для правки, как и любой другой шаблон).
- "Линия связи" исходного документа (одна колонка) здесь — три колонки (устройство/порт/соседнее
  устройство): колонка таблицы docx-блока — это всегда один путь поля, без склейки нескольких в
  одну ячейку (см. report_engine.py:column_value) — три узкие колонки не менее информативны одной
  широкой и не требуют новой возможности движка.

Источники данных таблиц 1 и 3 — те же "виртуальные" сущности конструктора, что и у шаблона
регламентированного отчёта (report_registry_rows.py: registry-connection-rows/registry-device-rows)
— читай данные оттуда как обычные плоские поля. Таблица 2 (VLAN) — обычная сущность реестра
(device-vlans), не виртуальная: PhysicalDeviceVLAN уже хранит IP-адрес/префикс прямо на записи,
поэтому специальная сущность для неё не нужна.

Параметр {{is_name}} — короткое имя/код информационной системы, для которой формируется приложение
(в исходном документе — буквально "ИС ТО"); подставляется в заголовки при формировании файла,
пользователь может изменить значение по умолчанию или ввести своё перед каждым формированием.
"""
