"""Код-ревью п.3.2 (высокая серьёзность): защита от Excel Formula Injection.

reporting.py (`ws.append(...)` в _populate_sheet1..4) и services/report_grid.py
(`xl_cell.value = cell["value"]`) записывают пользовательские текстовые поля в ячейки openpyxl
без проверки на ведущие символы формул. openpyxl автоматически помечает такую строку тегом
<f> (формула) в итоговом .xlsx — пользователь с правом записи может внести в имя устройства/ИС/
примечание значение вида "=HYPERLINK(...)", а получатель экспортированного отчёта (часто с
более высокими правами) выполнит эту формулу, просто открыв файл в Excel.

Единая точка защиты для ОБОИХ генераторов отчётов (стандартного reporting.py и
пользовательского конструктора report_grid.py) — чтобы правило было одно на проект, а не по
копии в каждом генераторе с риском разойтись при будущих правках одного из них.
"""
from __future__ import annotations

from typing import Any

# '=', '+', '-', '@' — все ведущие символы, которые Excel/openpyxl трактует как начало формулы.
_FORMULA_TRIGGER_CHARS = ("=", "+", "-", "@")

# Исключение: одиночный "-" (без ничего после) — не пользовательский ввод, а зарезервированный
# по всему проекту плейсхолдер "нет данных" (reporting.py: _link_purpose_label,
# _connection_row_values_list и т.п.). Формулой одиночный дефис быть не может (это не
# арифметическое выражение), а excel_safe на нём портил бы отображение каждой пустой ячейки
# ведущим апострофом. Любая строка вида "-что-то" (потенциальный payload вроде
# "-2+3+cmd|...") по-прежнему попадает под общее правило ниже и экранируется.
_SAFE_PLACEHOLDER = "-"


def excel_safe(value: Any) -> Any:
    """Если value — строка, начинающаяся с одного из символов-триггеров формулы, возвращает её
    с ведущим апострофом (Excel показывает такую ячейку как обычный текст, апостроф в
    отображении не виден). Нестроковые значения (числа, None, даты) возвращают как есть —
    формулой может стать только текстовая ячейка. Одиночный "-" (плейсхолдер "нет данных")
    — единственное исключение из общего правила, см. _SAFE_PLACEHOLDER.

    Пример вызова:
        excel_safe("=HYPERLINK(\"http://evil\")")  # -> "'=HYPERLINK(\"http://evil\")"
        excel_safe("Обычное имя устройства")         # -> "Обычное имя устройства" (без изменений)
        excel_safe("-")                               # -> "-" (плейсхолдер "нет данных", не формула)
        excel_safe(42)                                # -> 42 (не строка, изменений нет)
    """
    if value == _SAFE_PLACEHOLDER:
        return value
    if isinstance(value, str) and value.startswith(_FORMULA_TRIGGER_CHARS):
        return "'" + value
    return value


def excel_safe_row(row: list[Any]) -> list[Any]:
    """excel_safe(), применённый к каждой ячейке строки — используется перед каждым
    ws.append(row) в reporting.py, где строка всегда собрана как обычный python list."""
    return [excel_safe(cell) for cell in row]
