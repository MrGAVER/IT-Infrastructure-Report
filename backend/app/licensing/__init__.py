"""Лицензирование: подписанные ключи (Ed25519), привязка к хосту, временные и постоянные ключи.

Пакет намеренно не импортирует ``app.config`` и ничего не реэкспортирует: его использует и приложение, и
вендорский CLI (``tools/license_admin.py``), а конфиг при импорте создаёт каталоги данных.

Схема (подробности — docs/licensing.md):

* ``models``      — содержимое ключа (``LicensePayload``/``Binding``) и результат проверки (``LicenseReport``);
* ``codec``       — формат токена ``RIS1.<kid>.<payload>.<signature>``, подпись и проверка подписи;
* ``keys``        — набор встроенных ПУБЛИЧНЫХ ключей (приватный ключ в приложение не попадает никогда);
* ``context``     — что приложение знает о своём хосте: имя, IP-адреса, отпечаток машины, параметры;
* ``validator``   — чистая функция ``evaluate_token``: подпись → привязки → срок;
* ``clock_guard`` — защита от отката системных часов;
* ``manager``     — хранение ключа, кэш проверки, активация;
* ``middleware``  — принуждение на уровне HTTP (режим «только чтение» или полная блокировка).
"""
